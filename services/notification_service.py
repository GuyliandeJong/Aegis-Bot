import discord

from config.settings import settings
from services import activity_log
from utils import theme
from utils.logger import logger


class NotificationService:
    """
    Handles all Discord notifications generated by Aegis-Bot.

    Monitors use this service instead of directly interacting with
    Discord channels. This keeps notification formatting and delivery
    in one central location.
    """

    def __init__(self, bot):
        self.bot = bot

    async def _send(
        self,
        title: str,
        description: str,
        color: discord.Color,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
        level: str = "info",
    ):
        """Send a formatted notification to the configured alert channel."""

        channel = self.bot.get_channel(
            settings.ALERT_CHANNEL_ID
        )

        if channel is None:
            logger.error(
                "[NotificationService] Alert channel not found."
            )
            return

        embed = discord.Embed(
            title=title,
            description=description,
            color=color,
        )

        if fields:
            for name, value, inline in fields:
                embed.add_field(
                    name=name,
                    value=value,
                    inline=inline,
                )

        embed.timestamp = discord.utils.utcnow()

        embed.set_footer(
            text="Aegis-Bot"
        )

        await channel.send(
            content=content,
            embed=embed,
            allowed_mentions=discord.AllowedMentions(
                users=True
            ),
        )

        logger.info(
            "[NotificationService] Sent notification: %s",
            title,
        )

        activity_log.record("alert", level=level, title=title)

    async def info(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send an informational notification."""

        await self._send(
            title=title,
            description=description,
            color=theme.PRIMARY_COLOR,
            fields=fields,
            content=content,
            level="info",
        )

    async def warning(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a warning notification."""

        await self._send(
            title=title,
            description=description,
            color=theme.WARNING_COLOR,
            fields=fields,
            content=content,
            level="warning",
        )

    async def critical(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a critical notification."""

        await self._send(
            title=title,
            description=description,
            color=theme.ERROR_COLOR,
            fields=fields,
            content=content,
            level="critical",
        )

    async def recovered(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a recovery notification."""

        await self._send(
            title=title,
            description=description,
            color=theme.SUCCESS_COLOR,
            fields=fields,
            content=content,
            level="recovered",
        )

    async def success(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a successful-operation notification."""

        await self._send(
            title=title,
            description=description,
            color=theme.SUCCESS_COLOR,
            fields=fields,
            content=content,
            level="success",
        )