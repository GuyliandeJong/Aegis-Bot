def _bot_settings() -> set[str]:
    """Names of the bot's settings, from .env.example."""
    names = set()

    for line in (ROOT / ".env.example").read_text(encoding="utf-8").splitlines():
        name = line.split("=", 1)[0].strip()

        if "=" in line and name.isupper() and not line.startswith("#"):
            names.add(name)

    return names


def _run(name: str, data: str) -> tuple[bool, str, list[str]]:
    # Without the bot's own settings, so a check behaves the same inside
    # the real container as anywhere else and never reaches a real
    # service: settings from the environment are removed, and .env is
    # replaced by an empty file.
    settings = _bot_settings()
    environment = {
        key: value
        for key, value in os.environ.items()
        if key not in settings and not key.startswith("JELLYFIN_")
    }
    empty = Path(data) / "empty.env"
    empty.write_text("")
    environment["ENV_FILE"] = str(empty)
    environment["PYTHONPATH"] = os.pathsep.join(
        [str(ROOT), str(TESTS)]
    )
    environment["PYTHONIOENCODING"] = "utf-8"
    environment["PYTHONDONTWRITEBYTECODE"] = "1"
    environment["DATA_DIR"] = data
    # Checks with dates expect UTC; local time would move them across
    # summer time changes.
    environment["TZ"] = "UTC"

    try:
        result = subprocess.run(
            [sys.executable, str(TESTS / name)],
            cwd=ROOT,
            env=environment,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=300,
        )
    except subprocess.TimeoutExpired:
        return False, "", ["timed out after 300 seconds"]

    output = result.stdout + result.stderr
    problems = []

    if result.returncode != 0:
        problems.append(f"exit code {result.returncode}")

    for marker in FAILURE_MARKERS:
        if marker in output:
            problems.append(f"output contains {marker!r}")

    for line in EXPECTED[name]:
        if line not in output:
            problems.append(f"missing: {line}")

    return not problems, output, problems


def main() -> int:
    arguments = [a for a in sys.argv[1:] if not a.startswith("-")]
    verbose = "-v" in sys.argv[1:]

    names = [
        name
        for name in sorted(EXPECTED)
        if not arguments or any(a in name for a in arguments)
    ]

    failed = 0

    for name in names:
        passed, output, problems = run(name)

        print(f"{'PASS' if passed else 'FAIL'}  {name}")

        for problem in problems:
            print(f"        {problem}")

        if verbose or not passed:
            for line in output.rstrip().splitlines():
                print(f"        | {line}")

        failed += not passed

    print()
    print(f"{len(names) - failed} of {len(names)} checks passed.")

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
