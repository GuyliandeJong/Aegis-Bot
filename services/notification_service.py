import discord

from config.settings import settings
from services import activity_log, fluxer_webhook, maintenance
from utils import theme
from utils.logger import logger


class NotificationService:
    """
    Handles all Discord notifications generated by Aegis-Bot.

    Monitors use this service instead of directly interacting with
    Discord channels. This keeps notification formatting and delivery
    in one central location.
    """

    def __init__(self, bot):
        self.bot = bot

    async def _post(
        self,
        title: str,
        description: str,
        color: discord.Color,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """
        Post an embed in the configured alert channel.

        Returns the sent message, or None when the channel is missing.

        When FLUXER_WEBHOOK_URL is set, the same alert is also posted to
        Fluxer in the background; that never delays or breaks this one.
        """

        # Scheduled first, so Fluxer also gets alerts Discord misses.
        fluxer_webhook.start(
            title,
            description,
            color,
            fields,
            bot=self.bot,
        )

        channel = self.bot.get_channel(
            settings.ALERT_CHANNEL_ID
        )

        if channel is None:
            logger.error(
                "[NotificationService] Alert channel not found."
            )
            return

        embed = discord.Embed(
            title=title,
            description=description,
            color=color,
        )

        if fields:
            for name, value, inline in fields:
                embed.add_field(
                    name=name,
                    value=value,
                    inline=inline,
                )

        embed.timestamp = discord.utils.utcnow()

        embed.set_footer(
            text="Aegis-Bot"
        )

        return await channel.send(
            content=content,
            embed=embed,
            allowed_mentions=discord.AllowedMentions(
                users=True
            ),
        )

    async def _send(
        self,
        title: str,
        description: str,
        color: discord.Color,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
        level: str = "info",
        exempt: bool = False,
    ):
        """
        Send a formatted notification to the configured alert channel.

        During maintenance, levels in maintenance.MUTED_LEVELS are not
        posted (unless `exempt`) but still recorded in the activity
        log, so the weekly summary stays complete. Critical alerts are
        posted with "(during maintenance)" added to the title.

        Returns the sent message, or None when the channel is missing
        or the alert was muted.
        """

        # Report an expired maintenance before this alert, so the
        # alert is not muted by a maintenance that already ran out.
        await self.end_maintenance_if_expired()

        if maintenance.active():
            if level in maintenance.MUTED_LEVELS and not exempt:
                maintenance.mute(level, title)
                activity_log.record("alert", level=level, title=title)

                logger.info(
                    "[NotificationService] Muted during maintenance: %s",
                    title,
                )
                return

            if level == "critical":
                shown_title = f"{title} (during maintenance)"
            else:
                shown_title = title
        else:
            shown_title = title

        message = await self._post(
            title=shown_title,
            description=description,
            color=color,
            fields=fields,
            content=content,
        )

        if message is None:
            return

        logger.info(
            "[NotificationService] Sent notification: %s",
            title,
        )

        activity_log.record("alert", level=level, title=title)

        return message

    # ------------------------------------------------------------
    # Maintenance mode
    # ------------------------------------------------------------

    async def start_maintenance(
        self,
        minutes: int,
        reason: str,
        user_id: int,
    ) -> dict:
        """Start or extend maintenance and say so in the alert channel."""

        state, extended = maintenance.start(
            minutes,
            reason,
            str(user_id),
        )

        until = state["until"]
        description = (
            f"<@{user_id}> {'extended' if extended else 'started'} "
            f"maintenance until <t:{until}:t> (<t:{until}:R>).\n"
            "Warnings, recoveries and info messages are muted until "
            "then; critical alerts still come through."
        )

        if reason:
            description += f"\n\n**Reason:** {reason}"

        logger.info(
            "[NotificationService] Maintenance %s by %s until %s.",
            "extended" if extended else "started",
            user_id,
            until,
        )

        await self._post(
            title="🛠️ Maintenance "
            + ("Extended" if extended else "Started"),
            description=description,
            color=theme.PRIMARY_COLOR,
        )

        return state

    async def end_maintenance(
        self,
        user_id: int | None = None,
    ) -> dict | None:
        """
        End maintenance and post what was muted during it.

        `user_id` is who ended it early; None means it expired.
        Returns the ended state, or None when none was active.
        """

        state = maintenance.end()

        if state is None:
            return None

        total, titles = maintenance.muted_summary(state)

        if total:
            description = (
                f"Maintenance ended — {total} "
                f"alert{'s' if total != 1 else ''} muted:\n{titles}"
            )
        else:
            description = "Maintenance ended — no alerts were muted."

        if user_id is not None:
            ended = f"Ended early by <@{user_id}>."
        else:
            ended = f"Ran until <t:{state['until']}:t>."

        fields = [
            (
                "Started",
                f"<t:{state.get('started', state['until'])}:t> by "
                f"<@{state.get('started_by', '?')}> · {ended}",
                False,
            )
        ]

        counts = state.get("counts") or {}

        if counts:
            fields.append((
                "Muted per level",
                " · ".join(
                    f"{count} {level}"
                    for level, count in sorted(
                        counts.items(),
                        key=lambda item: -item[1],
                    )
                ),
                False,
            ))

        logger.info(
            "[NotificationService] Maintenance ended (%s); %s alerts muted.",
            "early" if user_id is not None else "expired",
            total,
        )

        await self._post(
            title="🛠️ Maintenance Ended",
            description=description,
            color=theme.SUCCESS_COLOR,
            fields=fields,
        )

        return state

    async def end_maintenance_if_expired(self) -> None:
        """Post the end message once maintenance has run out."""

        if maintenance.expired():
            await self.end_maintenance()

    async def info(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
        exempt: bool = False,
    ):
        """
        Send an informational notification.

        `exempt` posts it during maintenance too, for scheduled
        reports such as the weekly summary that are not alerts.
        """

        return await self._send(
            title=title,
            description=description,
            color=theme.PRIMARY_COLOR,
            fields=fields,
            content=content,
            level="info",
            exempt=exempt,
        )

    async def warning(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a warning notification."""

        return await self._send(
            title=title,
            description=description,
            color=theme.WARNING_COLOR,
            fields=fields,
            content=content,
            level="warning",
        )

    async def critical(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a critical notification."""

        return await self._send(
            title=title,
            description=description,
            color=theme.ERROR_COLOR,
            fields=fields,
            content=content,
            level="critical",
        )

    async def recovered(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a recovery notification."""

        return await self._send(
            title=title,
            description=description,
            color=theme.SUCCESS_COLOR,
            fields=fields,
            content=content,
            level="recovered",
        )

    async def success(
        self,
        title: str,
        description: str,
        *,
        fields: list[tuple[str, str, bool]] | None = None,
        content: str | None = None,
    ):
        """Send a successful-operation notification."""

        return await self._send(
            title=title,
            description=description,
            color=theme.SUCCESS_COLOR,
            fields=fields,
            content=content,
            level="success",
        )